import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"

const migrationPath = resolve(
  "supabase/migrations/20260908085542_mvp_foundation_data_model.sql",
)
const outputPath = resolve("src/types/mvp-database.generated.ts")
const sql = readFileSync(migrationPath, "utf8")

function splitDefinitions(body) {
  const definitions = []
  let current = ""
  let depth = 0
  let quoted = false

  for (let index = 0; index < body.length; index += 1) {
    const character = body[index]
    const next = body[index + 1]
    if (character === "'" && quoted && next === "'") {
      current += "''"
      index += 1
      continue
    }
    if (character === "'") quoted = !quoted
    if (!quoted && character === "(") depth += 1
    if (!quoted && character === ")") depth -= 1
    if (!quoted && depth === 0 && character === ",") {
      definitions.push(current.trim())
      current = ""
    } else {
      current += character
    }
  }
  if (current.trim()) definitions.push(current.trim())
  return definitions
}

function typescriptType(sqlType) {
  if (sqlType.startsWith("public.")) {
    return `MvpEnums["${sqlType.slice("public.".length)}"]`
  }
  if (["integer", "bigint"].includes(sqlType)) return "number"
  if (sqlType === "boolean") return "boolean"
  if (sqlType === "jsonb") return "MvpJson"
  return "string"
}

const enumEntries = [...sql.matchAll(/create type public\.(\w+) as enum \(([^;]+)\);/g)].map(
  ([, name, values]) => ({
    name,
    values: [...values.matchAll(/'([^']+)'/g)].map((match) => match[1]),
  }),
)

const tables = [...sql.matchAll(/create table public\.(\w+) \(([\s\S]*?)\n\);/g)].map(
  ([, name, body]) => {
    const definitions = splitDefinitions(body)
    const columns = definitions.flatMap((definition) => {
      const match = definition.match(
        /^(\w+)\s+(uuid|text|integer|bigint|boolean|date|timestamptz|jsonb|public\.\w+)\b/i,
      )
      if (!match) return []
      const [, columnName, sqlType] = match
      const nullable = !/\bnot null\b/i.test(definition)
      const optionalInsert = nullable || /\bdefault\b/i.test(definition)
      return [{ columnName, type: typescriptType(sqlType), nullable, optionalInsert }]
    })
    const relationships = definitions.flatMap((definition, index) => {
      const match = definition.match(
        /^foreign key \(([^)]+)\) references public\.(\w+)\(([^)]+)\)/i,
      )
      if (!match) return []
      const columns = match[1].split(",").map((value) => value.trim())
      const referencedColumns = match[3].split(",").map((value) => value.trim())
      return [{
        name: `${name}_${columns.join("_")}_fkey_${index}`,
        columns,
        referencedRelation: match[2],
        referencedColumns,
      }]
    })
    return { name, columns, relationships }
  },
)

const lines = [
  "// Generated by scripts/generate-mvp-foundation-types.mjs. Do not edit manually.",
  "export type MvpJson = string | number | boolean | null | { [key: string]: MvpJson | undefined } | MvpJson[]",
  "",
  "export type MvpEnums = {",
]

for (const entry of enumEntries) {
  lines.push(`  ${entry.name}: ${entry.values.map((value) => JSON.stringify(value)).join(" | ")}`)
}
lines.push("}", "", "export const MvpEnumConstants = {")
for (const entry of enumEntries) {
  lines.push(`  ${entry.name}: [${entry.values.map((value) => JSON.stringify(value)).join(", ")}],`)
}
lines.push("} as const", "", "export type MvpTables = {")

for (const table of tables) {
  lines.push(`  ${table.name}: {`, "    Row: {")
  for (const column of table.columns) {
    lines.push(`      ${column.columnName}: ${column.type}${column.nullable ? " | null" : ""}`)
  }
  lines.push("    }", "    Insert: {")
  for (const column of table.columns) {
    lines.push(`      ${column.columnName}${column.optionalInsert ? "?" : ""}: ${column.type}${column.nullable ? " | null" : ""}`)
  }
  lines.push("    }", "    Update: {")
  for (const column of table.columns) {
    lines.push(`      ${column.columnName}?: ${column.type}${column.nullable ? " | null" : ""}`)
  }
  lines.push("    }", "    Relationships: [")
  for (const relationship of table.relationships) {
    lines.push(
      "      {",
      `        foreignKeyName: ${JSON.stringify(relationship.name)}`,
      `        columns: [${relationship.columns.map(JSON.stringify).join(", ")}]`,
      "        isOneToOne: false",
      `        referencedRelation: ${JSON.stringify(relationship.referencedRelation)}`,
      `        referencedColumns: [${relationship.referencedColumns.map(JSON.stringify).join(", ")}]`,
      "      },",
    )
  }
  lines.push("    ]", "  }")
}
lines.push("}", "")

const generated = lines.join("\n")
if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8")
  if (current !== generated) {
    console.error("Generated MVP database types are out of date.")
    process.exit(1)
  }
} else {
  writeFileSync(outputPath, generated)
}
